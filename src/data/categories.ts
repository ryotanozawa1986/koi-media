const idPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

function assertCategories(list: CategoryDef[]): void {
  const seen = new Set<string>();
  for (const category of list) {
    if (!idPattern.test(category.id) || category.id === 'page') {
      throw new Error(`カテゴリ id が不正です: ${category.id}`);
    }
    if (seen.has(category.id)) {
      throw new Error(`カテゴリ id が重複しています: ${category.id}`);
    }
    seen.add(category.id);
    if (!category.name.trim()) {
      throw new Error(`カテゴリ ${category.id} の name が空です`);
    }
    if (category.description.length < 40 || category.description.length > 160) {
      throw new Error(
        `カテゴリ ${category.id} の description は40〜160文字にしてください（いま ${category.description.length}文字）`,
      );
    }
    if (category.lead.length < 16 || category.lead.length > 80) {
      throw new Error(
        `カテゴリ ${category.id} の lead は16〜80文字にしてください（いま ${category.lead.length}文字）`,
      );
    }
    if (category.paragraphs.length < 2 || category.paragraphs.some((paragraph) => paragraph.trim().length < 40)) {
      throw new Error(`カテゴリ ${category.id} の paragraphs は、40文字以上の段落を2つ以上書いてください`);
    }
    if (category.pillarSlug && !idPattern.test(category.pillarSlug)) {
      throw new Error(`カテゴリ ${category.id} の pillarSlug が不正です: ${category.pillarSlug}`);
    }
  }
}

assertCategories(categories);
